// Collect every solve()/worked() card from the chapters by running each page's inline script with stubs.
// Usage: node math/tools/cards.js            -> prints a summary
//        node math/tools/cards.js --exam     -> writes math/exam/2022-23.html, 2023-24.html, 2024-25.html
const fs = require('fs'), path = require('path');
const ROOT = path.join(__dirname, '..');
const files = ['vc', 'cc', 'pde'].flatMap(d => fs.existsSync(path.join(ROOT, d)) ? fs.readdirSync(path.join(ROOT, d)).filter(f => f.endsWith('.html')).sort().map(f => d + '/' + f) : []);
function cardsOf(file) {
  const html = fs.readFileSync(path.join(ROOT, file), 'utf8');
  const js = (html.match(/<script>\n?([\s\S]*?)<\/script>/g) || []).map(s => s.replace(/<\/?script>/g, '')).join('\n');
  const out = [], el = new Proxy({}, { get: () => () => el, set: () => true });
  const stub = { solve: (s, c) => out.push({ ...c, kind: 'solve' }), worked: (s, c) => out.push({ ...c, kind: 'worked' }) };
  const names = ['solve', 'worked', '$', 'document', 'tex', 'quiz', 'flashcards', 'stepper', 'ask'];
  try { new Function(...names, js)(stub.solve, stub.worked, () => el, el, () => {}, () => {}, () => {}, () => {}, () => {}); }
  catch (e) { console.error('ERR', file, e.message); }
  return out.map(c => ({ ...c, file }));
}
const all = files.flatMap(cardsOf);
const title = f => (fs.readFileSync(path.join(ROOT, f), 'utf8').match(/<h1>(.*?)<\/h1>/) || [, f])[1];
if (!process.argv.includes('--exam')) {
  for (const f of files) { const c = all.filter(x => x.file === f); console.log(f.padEnd(40), 'cards', c.length, 'must', c.filter(x => x.must && x.kind === 'solve').length); }
  console.log('total', all.length, 'must', all.filter(x => x.must && x.kind === 'solve').length);
  process.exit(0);
}
// ---------- exam pages: one row per past-paper card, sorted by question number ----------
const YEARS = ['2024-25', '2023-24', '2022-23'];
const qkey = s => { const m = /Q\s*(\d)\s*\(?([a-d])?\)?(?:\s*\((i+v?|v)\))?/.exec(s) || []; return [+(m[1] || 9), m[2] || '', m[3] || '']; };
for (const y of YEARS) {
  const rows = [];
  for (const c of all) {
    if (c.kind !== 'solve' || !c.src) continue;
    for (const part of String(c.src).split(/[;,=+]| and /)) {
      if (!part.includes(y) && !part.includes(y.replace('20', '').replace('-', '-'))) continue;
      if (/MATH\s*1[0-9]{2}|MATH\s*245|ME-|CT/i.test(part.slice(0, part.indexOf(y)))) continue;
      rows.push({ k: qkey(part.slice(part.indexOf(y))), c });
      break;
    }
  }
  rows.sort((a, b) => a.k[0] - b.k[0] || a.k[1].localeCompare(b.k[1]) || a.k[2].localeCompare(b.k[2]));
  const seen = new Set(), list = rows.filter(r => { const id = r.c.file + r.c.id; if (seen.has(id)) return false; seen.add(id); return true; });
  let h = '', lastQ = 0;
  for (const { k, c } of list) {
    if (k[0] !== lastQ) { h += `${lastQ ? '</ol>' : ''}<h2>${k[0] === 9 ? 'Other parts' : (k[0] <= 4 ? 'Section A · ' : 'Section B · ') + 'Question ' + k[0]}</h2><ol class="paper">`; lastQ = k[0]; }
    h += `<li><div class="freq">${c.src} · <a href="../${c.file}#q-${c.id}">${title(c.file)}</a></div><div>${c.q}</div></li>`;
  }
  if (lastQ) h += '</ol>';
  const page = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Term final ${y} · MATH 241</title>
<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Source+Serif+4:ital,opsz,wght@0,8..60,400;0,8..60,600;0,8..60,700;1,8..60,400&family=IBM+Plex+Mono:wght@400;600&display=swap">
<link rel="stylesheet" href="../assets/book.css">
</head>
<body>
<main>
<div class="eyebrow">Exam · past paper (generated by tools/cards.js, do not edit)</div>
<h1>Term final ${y}</h1>
<p class="lede">Every question of this paper, in order. Each links to its card in the chapter, where you solve it, open the steps and grade it.</p>
<div class="hint"><b>Timed practice:</b> pick 3 questions from one section, 90 minutes, on paper, no book. Then open each card, mark yourself against the steps, and grade it there.</div>
${h || '<p>No cards found for this year.</p>'}
</main>
<script src="../assets/book.js"></script><script src="../assets/math.js"></script>
</body></html>
`;
  fs.mkdirSync(path.join(ROOT, 'exam'), { recursive: true });
  fs.writeFileSync(path.join(ROOT, 'exam', y + '.html'), page);
  console.log(y, list.length, 'questions');
}
